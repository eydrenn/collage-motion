// Commands: art, library, backgrounds.
import { readFileSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { generate, compose } from "../lib/generate.mjs";
import { createContext } from "../lib/paper.mjs";
import { mosaic } from "../lib/background.mjs";
import { SKILL, PROJECT, LIBRARY, OUT, FONT_CSS, outDir, readArgs, loadKit, artNames, launchBrowser, shoot, UsageError } from "../lib/env.mjs";

const sheetPage = (panels, background = "#CDBE9C") => `<!doctype html><meta charset="utf-8"><style>${FONT_CSS}
html,body{margin:0;background:#fff}
#f{display:inline-flex;gap:0;align-items:flex-end;padding:36px;flex-wrap:wrap;max-width:2600px;background:${background}}
.q{padding:18px 22px;display:flex;flex-direction:column;align-items:center}
.q small{font:500 13px ui-monospace,Menlo,monospace;color:#5d5443;margin-top:8px}
svg{display:block}
</style><div id="f">${panels.map((p) => `<div class="q">${p.svg}${p.label ? `<small>${p.label}</small>` : ""}</div>`).join("")}</div>`;

// the first comment of the source is the art's one-line description
const describe = (source) => ((source.match(/<!--\s*([\s\S]*?)\s*-->/) || [])[1] || "").replace(/\s+/g, " ");

export async function art(argv) {
  const a = readArgs(argv), seed = Number(a.value("seed", 1)), all = a.flag("all");
  const own = join(PROJECT, "art");
  const files = all ? artNames(own).map((n) => join(own, `${n}.svg`)) : a.rest.map((f) => resolve(f));
  if (!files.length) throw new UsageError(all ? "there is no SVG in ./art yet" : "give one or more SVG files, or --all for everything in ./art");
  const kit = loadKit(), dir = outDir("art"), browser = await launchBrowser(), panels = [];
  for (const file of files) {
    const name = basename(file).replace(/\.svg$/, "");
    const g = generate(readFileSync(file, "utf8"), name, kit, { seed });
    const svg = compose(g);
    writeFileSync(join(dir, `${name}.svg`), svg);
    writeFileSync(join(dir, `${name}.json`), JSON.stringify(g.meta, null, 1) + "\n");
    await shoot(browser, sheetPage([{ svg }]), join(dir, `${name}.png`));
    console.log(`${name}: ${g.meta.pieces} pieces, parts: ${g.meta.parts.map((p) => p.id).join(", ")} -> out/art/${name}.png`);
    for (const w of [...new Set(g.warnings)]) console.log(`  warning: ${w}`);
    panels.push({ svg, label: `${name} · ${g.width}×${g.height} · ${g.meta.pieces} pieces` });
  }
  if (all) { await shoot(browser, sheetPage(panels), join(OUT, "art-sheet.png"), { scale: 1 }); console.log("sheet: out/art-sheet.png"); }
  await browser.close();
}

export async function library(argv) {
  const a = readArgs(argv), sheet = a.flag("sheet"), catalog = a.flag("write-catalog");
  const kit = loadKit(), panels = [], rows = [];
  for (const name of artNames(LIBRARY)) {
    const source = readFileSync(join(LIBRARY, `${name}.svg`), "utf8"), g = generate(source, name, kit);
    const parts = g.meta.parts.map((p) => p.id).join(", ");
    rows.push({ name, size: `${g.width}×${g.height}`, parts, about: describe(source) });
    panels.push({ svg: compose(g), label: `${name} · ${g.width}×${g.height}` });
  }
  if (!catalog) for (const r of rows) console.log(`${r.name.padEnd(16)} ${r.size.padEnd(9)} ${r.about}  [parts: ${r.parts}]`);
  console.log(`${rows.length} library art. People are not art: see the cast (\`collage cast\`).`);
  if (catalog) {
    writeFileSync(join(SKILL, "references/library.md"), `# Library art\n\nGenerated by \`collage library --write-catalog\` from the first comment of each file in \`assets/src/\`. Do not edit by hand.\n\n${rows.length} pieces of art. Use the name in a layer: \`{ "type": "art", "name": "clock" }\`. A file with the same name in your project's \`./art\` folder wins over the library.\n\n| Name | Size | Parts | What it is |\n|---|---|---|---|\n${rows.map((r) => `| \`${r.name}\` | ${r.size} | ${r.parts} | ${r.about} |`).join("\n")}\n`);
    console.log("catalog: references/library.md");
  }
  if (sheet) {
    const browser = await launchBrowser();
    outDir();
    await shoot(browser, sheetPage(panels), join(OUT, "library-sheet.png"), { scale: 1 });
    await browser.close();
    console.log("sheet: out/library-sheet.png");
  }
}

export async function backgrounds(argv) {
  const a = readArgs(argv), seed = Number(a.value("seed", 1)), width = 540, height = 960;
  const kit = loadKit(), browser = await launchBrowser();
  const panels = kit.palette.backgrounds.map((name) => {
    const ctx = createContext(`bg-${name}`, kit, seed);
    const body = mosaic({ width, height, color: kit.palette.paper[name], seed }, ctx);
    return { svg: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width / 1.6}" height="${height / 1.6}"><defs>${ctx.defs()}</defs>${body}</svg>`, label: name };
  });
  outDir();
  await shoot(browser, sheetPage(panels, "#fff"), join(OUT, "backgrounds-sheet.png"), { scale: 1 });
  await browser.close();
  console.log("sheet: out/backgrounds-sheet.png");
}
